// Writes src-tauri/THIRD-PARTY-NOTICES.md: every Rust crate Raven is built from and every
// npm package that ends up in its bundle, grouped by licence, each distinct licence text
// once with the packages that carry it. The installer bundles the file and Settings shows
// it, so run this before a release:
//
//   bun scripts/third-party-notices.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { build } from "vite";

const desktop = resolve(import.meta.dir, "..");
const output = join(desktop, "src-tauri", "THIRD-PARTY-NOTICES.md");
const LICENCE_FILE = /^(licen[cs]e|copying|notice|unlicense)/i;
const NO_TEXT = "The licence text is not published with these packages.";

/** Licence expression -> licence text -> "name version" of the packages carrying it. */
const groups = new Map<string, Map<string, Set<string>>>();

function add(name: string, version: string, licence: string, dir: string) {
  const texts = readdirSync(dir)
    .filter((file) => LICENCE_FILE.test(file) && statSync(join(dir, file)).isFile())
    .map((file) => readFileSync(join(dir, file), "utf8").replaceAll("\r\n", "\n").trim());
  const byText = groups.get(licence) ?? new Map<string, Set<string>>();
  groups.set(licence, byText);
  for (const text of texts.length ? texts : [NO_TEXT]) {
    const packages = byText.get(text) ?? new Set<string>();
    byText.set(text, packages.add(`${name} ${version}`));
  }
}

// Rust: the crates reachable from Raven through normal dependencies, for every platform.
const cargo = Bun.spawnSync(["cargo", "metadata", "--format-version", "1", "--locked"], {
  cwd: join(desktop, "src-tauri"),
  stdout: "pipe",
  stderr: "inherit",
});
if (!cargo.success) throw new Error("cargo metadata failed");
const metadata = JSON.parse(cargo.stdout.toString());
const crates = new Map<string, any>(metadata.packages.map((crate: any) => [crate.id, crate]));
const nodes = new Map<string, any>(metadata.resolve.nodes.map((node: any) => [node.id, node]));
const reached = new Set<string>();
const pending: string[] = [metadata.resolve.root];
while (pending.length) {
  const id = pending.pop()!;
  if (reached.has(id)) continue;
  reached.add(id);
  for (const dependency of nodes.get(id).deps) {
    if (dependency.dep_kinds.some((kind: any) => kind.kind === null)) pending.push(dependency.pkg);
  }
}
for (const id of reached) {
  const crate = crates.get(id);
  // Crates without a source are local: Raven itself, which is not third-party, and the
  // copies vendored under src-tauri/vendor, which are.
  if (crate.source || id !== metadata.resolve.root) {
    add(crate.name, crate.version, crate.license, dirname(crate.manifest_path));
  }
}

// Frontend: the packages the bundler really included, found by building it.
const bundle = (await build({ root: desktop, logLevel: "silent", build: { write: false } })) as any;
const packageDirs = new Set<string>();
for (const chunk of [bundle].flat().flatMap((result) => result.output)) {
  for (const [id, module] of Object.entries<any>(chunk.modules ?? {})) {
    // Plugins prefix virtual modules with a null character and suffix a query.
    const path = id.replace(/^\0/, "").replaceAll("\\", "/").split("?")[0];
    const at = path.lastIndexOf("/node_modules/");
    // CSS-only font packages have no rendered JavaScript but ship their assets.
    if (at < 0 || (module.renderedLength === 0 && !/\.(css|scss)$/.test(path))) continue;
    const [first, second] = path.slice(at + "/node_modules/".length).split("/");
    packageDirs.add(`${path.slice(0, at)}/node_modules/${first.startsWith("@") ? `${first}/${second}` : first}`);
  }
}
// The emoji font is bundled from src/assets as a patched copy of this package's font
// (scripts/patch-twemoji.py), so the bundle never references the package itself.
packageDirs.add(join(desktop, "node_modules", "twemoji-colr-font").replaceAll("\\", "/"));
for (const dir of packageDirs) {
  const { name, version, license } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  add(name, version, typeof license === "string" ? license : license?.type ?? "Unknown", dir);
}

let notices = `# Third-party notices

Raven is built on open-source software. These are the projects it uses and their licences.
Generated by scripts/third-party-notices.ts; do not edit by hand.
`;
for (const [licence, byText] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
  notices += `\n## ${licence}\n`;
  for (const [text, packages] of [...byText].sort((a, b) => b[1].size - a[1].size)) {
    const indented = text.replace(/^/gm, "    ").replace(/ +$/gm, "");
    notices += `\nUsed by: ${[...packages].sort().join(", ")}\n\n${indented}\n`;
  }
}
writeFileSync(output, notices);
console.log(`${[...groups.values()].flatMap((byText) => [...byText.values()]).length} licence texts in ${output}`);
